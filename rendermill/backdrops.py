"""Backdrop resolution for core.py's video-slide / animated-backdrop lanes.

The canon manifest is ``library_index.json``, generated by the backdrops
bridge (``marketing/engine/backdrops/index.py`` → ``write_index``). This
module reads that manifest and resolves a ``(preset, orientation, palette)``
to an mp4 path. It is stdlib-only and read-only: it never writes the index
and never touches the mp4/json assets.

The index lives in the sibling repo at ``<rendermill>/../backdrops/library/``.
Point ``VIIY_BACKDROPS_INDEX`` at an alternate ``library_index.json`` to
override that location (tests, CI, vendored checkouts).

Canon manifest schema: ``viiy-backdrops/library-index/1`` with
``{asset_count, library_dir, presets, orientations, by_preset}`` where
``by_preset[preset][orientation]`` carries ``{mp4, palette, width, height,
duration_s, seed, hash, mp4_exists, json}``.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any, Dict, List, Optional

# <repo>/rendermill/backdrops.py -> parents[1] is the rendermill repo root.
_REPO_ROOT = Path(__file__).resolve().parents[1]
_DEFAULT_INDEX = _REPO_ROOT.parent / "backdrops" / "library" / "library_index.json"

# rendermill orientation (config `orientation`, CLI --orientation) -> backdrops
# library orientation. `_dims` treats anything except "short" as landscape, so
# we mirror that: only explicit portrait-ish names map to "portrait".
ORIENTATION_MAP = {
    "horizontal": "landscape",
    "landscape": "landscape",
    "short": "portrait",
    "vertical": "portrait",
    "portrait": "portrait",
}

_index_cache: Optional[Dict[str, Any]] = None
_index_path: Optional[Path] = None


def index_path() -> Path:
    env = os.environ.get("VIIY_BACKDROPS_INDEX")
    return Path(env) if env else _DEFAULT_INDEX


def load_index() -> Dict[str, Any]:
    """Load (and cache) the canon library_index.json manifest."""
    global _index_cache, _index_path
    p = index_path()
    if _index_cache is None or _index_path != p:
        _index_cache = json.loads(Path(p).read_text(encoding="utf-8"))
        _index_path = p
    assert _index_cache is not None
    return _index_cache


def presets() -> List[str]:
    return list(load_index().get("presets", []))


def resolve(preset: Optional[str] = None, orientation: Optional[str] = None,
            palette: Optional[str] = None) -> List[Dict[str, Any]]:
    """Return matching entries from the canon index (match-all; filters optional)."""
    idx = load_index()
    out: List[Dict[str, Any]] = []
    for pname, orients in idx.get("by_preset", {}).items():
        if preset and pname != preset:
            continue
        for oname, entry in orients.items():
            if orientation and oname != orientation:
                continue
            if palette and entry.get("palette") != palette:
                continue
            out.append(dict(entry))
    return out


def orientation_for(rendermill_orientation: str) -> str:
    """Map a rendermill orientation name to a backdrops orientation name."""
    return ORIENTATION_MAP.get(rendermill_orientation, "landscape")


def resolve_mp4(preset: str, orientation: str,
                palette: Optional[str] = None) -> Path:
    """Resolve one backdrop mp4 path. Raises FileNotFoundError if absent."""
    matches = resolve(preset, orientation, palette)
    if not matches:
        detail = f"preset={preset!r} orientation={orientation!r}"
        if palette:
            detail += f" palette={palette!r}"
        raise FileNotFoundError(f"no backdrop in library index for {detail}")
    mp4 = Path(matches[0]["mp4"])
    if not mp4.exists():
        raise FileNotFoundError(f"backdrop mp4 missing on disk: {mp4}")
    return mp4


def apply_backdrop(slide: Dict[str, Any], *, orientation: str,
                   default_preset: Optional[str] = None,
                   default_palette: Optional[str] = None) -> Optional[Path]:
    """Resolve `slide`'s backdrop descriptor and set ``slide["backdrop"]`` to an
    absolute mp4 path when a preset resolves. Returns the resolved path (or None).

    Precedence (highest first):
      1. ``slide["backdrop"]`` as a dict ``{"preset": ..., "orientation"?,
         "palette"?}``.
      2. ``slide["backdrop_preset"]`` (str) + optional ``slide["backdrop_palette"]``.
      3. ``slide["backdrop"]`` as a string naming a known library preset.
      4. ``default_preset`` (project-level ``backdrop.preset`` config).

    An explicit ``slide["backdrop"]`` path string (not a preset name) is left
    untouched — the existing project/workdir-relative path resolution in
    ``ffmpeg_video.make_slide_video`` still owns it. Nothing here duplicates
    the mp4 paths; they come straight out of the canon manifest.
    """
    lib_orientation = orientation_for(orientation)

    bd = slide.get("backdrop")
    if isinstance(bd, dict):
        preset = bd.get("preset") or bd.get("name")
        if not preset:
            raise ValueError("slide backdrop dict requires a 'preset' key")
        path = resolve_mp4(
            preset,
            bd.get("orientation") or lib_orientation,
            bd.get("palette"),
        )
        slide["backdrop"] = str(path)
        return path

    preset = slide.get("backdrop_preset")
    if preset:
        path = resolve_mp4(preset, lib_orientation, slide.get("backdrop_palette"))
        slide["backdrop"] = str(path)
        return path

    if isinstance(bd, str) and bd in presets():
        path = resolve_mp4(bd, lib_orientation, default_palette)
        slide["backdrop"] = str(path)
        return path

    if default_preset:
        path = resolve_mp4(default_preset, lib_orientation, default_palette)
        slide["backdrop"] = str(path)
        return path

    return None
